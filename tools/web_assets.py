"""Embed the WebUI locally, without a network minification service."""

import gzip
import hashlib
from io import BytesIO
from pathlib import Path
from tempfile import NamedTemporaryFile


def _atomic_write(path, content):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with NamedTemporaryFile(dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        try:
            stream.write(content)
            stream.close()
            temporary.replace(path)
        finally:
            temporary.unlink(missing_ok=True)


def prepare_web_assets(project_dir):
    """Return True when the header changed; preserve source bytes inside gzip."""
    project_dir = Path(project_dir)
    source = project_dir / "embedded_resources/web_interface"
    files = sorted(p for p in source.iterdir() if p.suffix in (".html", ".css", ".js"))
    if not files:
        raise ValueError(f"No WebUI assets found in {source}")
    lines = [
        "#ifndef WEB_FILES_H\n#define WEB_FILES_H\n\n#include <Arduino.h>\n\n",
        "// Generated by tools/web_assets.py. Edit embedded_resources/web_interface instead.\n\n",
    ]
    names = set()
    for path in files:
        name = path.name.replace(".", "_")
        if not name.isascii() or not name.isidentifier() or name in names:
            raise ValueError(f"Invalid or duplicate C identifier for WebUI asset: {path.name}")
        names.add(name)
        output = BytesIO()
        with gzip.GzipFile(filename="", mode="wb", fileobj=output, mtime=0) as stream:
            stream.write(path.read_bytes())
        data = output.getvalue()
        lines.append(f"const uint8_t {name}[] PROGMEM = {{\n")
        for offset in range(0, len(data), 15):
            lines.append("  " + ", ".join(f"0x{b:02X}" for b in data[offset:offset + 15]) + ",\n")
        lines.append(f"}};\nconst uint32_t {name}_size = {len(data)};\n\n")
    lines.append("#endif // WEB_FILES_H\n")
    header = "".join(lines).encode("utf-8")
    destination = project_dir / "include/webFiles.h"
    changed = not destination.is_file() or destination.read_bytes() != header
    if changed:
        _atomic_write(destination, header)
    _atomic_write(source / "checksum.sha256", hashlib.sha256(header).hexdigest().encode("ascii"))
    return changed


if __name__ == "__main__":
    changed = prepare_web_assets(Path(__file__).resolve().parents[1])
    print("WebUI header generated" if changed else "WebUI header unchanged")
